const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.resolve(__dirname, "..");
const propertySource = fs.readFileSync(path.join(root, "assets", "properties", "properties.js"), "utf8");
const context = { window: {} };
vm.runInNewContext(propertySource, context);

const properties = context.window.PONASA_PROPERTIES;
const existingCoordinates = context.window.PONASA_PROPERTY_COORDINATES;
const countyRecordEndpoint = "https://web.bcpa.net/bcpaclient/search.aspx/getParcelInformation";
const parcelEndpoint = "https://services.arcgis.com/JMAJrTsHNLrSsWf5/arcgis/rest/services/Parcels/FeatureServer/0/query";
const requestHeaders = {
  "content-type": "application/json; charset=utf-8",
  "user-agent": "Mozilla/5.0",
  referer: "https://web.bcpa.net/bcpaclient/search.aspx",
  origin: "https://web.bcpa.net",
};

const groupsOf = (items, size) => Array.from(
  { length: Math.ceil(items.length / size) },
  (_, index) => items.slice(index * size, (index + 1) * size),
);

const fetchPropertyDetails = async () => {
  const details = {};
  for (const group of groupsOf(properties, 8)) {
    await Promise.all(group.map(async (property) => {
      const folio = property.folio.replace(/-/g, "");
      const response = await fetch(countyRecordEndpoint, {
        method: "POST",
        headers: requestHeaders,
        body: JSON.stringify({ folioNumber: folio, taxyear: String(new Date().getFullYear()), action: "CURRENT", use: "" }),
      });
      if (!response.ok) throw new Error(`County record request failed for ${folio}: ${response.status}`);
      const payload = await response.json();
      const record = payload?.d?.parcelInfok__BackingField?.[0];
      if (!record) throw new Error(`County record missing for ${folio}`);
      details[property.folio] = {
        type: record.useCode || null,
        yearBuilt: record.actualAge || null,
        buildingSqFt: Number(record.bldgSqFT) || null,
        totalSqFt: Number(record.bldgTotSqFootage) || null,
        underAirSqFt: Number(record.bldgUnderAirFootage) || null,
        lot: record.landCalcFact1 || null,
        units: Number(record.units) || null,
        beds: Number(record.beds) || null,
        baths: Number(record.baths) || null,
      };
    }));
  }
  return details;
};

const fetchParcelCoordinates = async () => {
  const folios = properties.map((property) => property.folio.replace(/-/g, ""));
  const url = new URL(parcelEndpoint);
  url.searchParams.set("where", `FOLIO IN (${folios.map((folio) => `'${folio}'`).join(",")})`);
  url.searchParams.set("outFields", "FOLIO");
  url.searchParams.set("returnGeometry", "false");
  url.searchParams.set("returnCentroid", "true");
  url.searchParams.set("outSR", "4326");
  url.searchParams.set("f", "json");
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Parcel geometry request failed: ${response.status}`);
  const payload = await response.json();
  const coordinates = {};
  (payload.features || []).forEach((feature) => {
    const property = properties.find((item) => item.folio.replace(/-/g, "") === feature.attributes.FOLIO);
    if (!property || !feature.centroid) return;
    coordinates[property.folio] = [
      Number(feature.centroid.y.toFixed(6)),
      Number(feature.centroid.x.toFixed(6)),
    ];
  });

  properties.forEach((property) => {
    if (!coordinates[property.folio] && existingCoordinates[property.folio]) {
      coordinates[property.folio] = existingCoordinates[property.folio];
    }
  });
  return coordinates;
};

const main = async () => {
  const [details, coordinates] = await Promise.all([
    fetchPropertyDetails(),
    fetchParcelCoordinates(),
  ]);
  const output = `/* Generated by tools/sync-property-data.js from Broward County public records. */\nwindow.PONASA_PROPERTY_DETAILS = ${JSON.stringify(details, null, 2)};\n\nwindow.PONASA_PARCEL_COORDINATES = ${JSON.stringify(coordinates, null, 2)};\n`;
  fs.writeFileSync(path.join(root, "assets", "properties", "property-details.js"), output);
  const propertySlug = (property) => property.address
    .normalize("NFKD")
    .toLowerCase()
    .replace(/#/g, " unit ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  const staticPaths = ["/", "/portfolio", "/company", "/locations", "/contact", "/privacy-policy", "/terms", "/accessibility", "/sitemap", "/usa", "/italy", "/colombia"];
  const urls = [
    ...staticPaths,
    ...properties.map((property) => `/portfolio/${propertySlug(property)}`),
  ];
  const lastModified = new Date().toISOString().slice(0, 10);
  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.map((url) => `  <url><loc>https://ponasa.com${url}</loc><lastmod>${lastModified}</lastmod></url>`).join("\n")}\n</urlset>\n`;
  fs.writeFileSync(path.join(root, "sitemap.xml"), sitemap);
  console.log(`Saved ${Object.keys(details).length} property records, ${Object.keys(coordinates).length} map points, and ${urls.length} sitemap URLs.`);
};

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
